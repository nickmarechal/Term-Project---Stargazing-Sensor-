#!/usr/bin/env python3
"""Writes tests/data/ephemeris_reference.inc from NASA/JPL Horizons.

Development tool only: run once by hand, and the output is committed. The
device never calls this or any other network service (spec 3.3). Horizons is
public reference data, used here only to check our own math.

usage: python3 tools/fetch_ephemeris_reference.py
"""
import json
import subprocess
import time
import urllib.parse

API = "https://ssd.jpl.nasa.gov/api/horizons.api"
OUT = "tests/data/ephemeris_reference.inc"
BATCH = 20

# 2026-01-01T00:00:00Z, then a step that moves through the hours of the day and
# the phases of the moon: 18 d 7 h 13 m 17 s.
START = 1767225600
STEP = 18 * 86400 + 7 * 3600 + 13 * 60 + 17

# name, east longitude, latitude, height in km, how many times.
# Fort Collins matches EPHEM_SITE_FORT_COLLINS. Sydney is only there to prove
# the site is really used (south, and east of Greenwich).
SITES = [("FORT_COLLINS", -105.08, 40.59, 1.525, 60),
         ("SYDNEY", 151.21, -33.87, 0.058, 10)]


def jd(unix_s):
    return unix_s / 86400.0 + 2440587.5


def query(body, quantities, lon, lat, km, times):
    params = {
        "format": "json", "COMMAND": f"'{body}'", "OBJ_DATA": "'NO'",
        "MAKE_EPHEM": "'YES'", "EPHEM_TYPE": "'OBSERVER'",
        "CENTER": "'coord@399'", "COORD_TYPE": "'GEODETIC'",
        "SITE_COORD": f"'{lon},{lat},{km}'",
        "TLIST_TYPE": "'JD'", "TIME_TYPE": "'UT'",
        "TLIST": ",".join(f"'{jd(t):.9f}'" for t in times),
        "QUANTITIES": f"'{quantities}'", "ANG_FORMAT": "'DEG'",
        "APPARENT": "'AIRLESS'", "CAL_FORMAT": "'JD'",
        "CSV_FORMAT": "'YES'", "EXTRA_PREC": "'YES'",
    }
    url = API + "?" + urllib.parse.urlencode(params)
    # curl rather than urllib: python.org's Python on macOS has no CA bundle
    # until it is set up by hand, and certificate checks stay on either way.
    done = subprocess.run(["curl", "-sS", "--fail", "-m", "60", url],
                          check=True, capture_output=True)
    text = json.loads(done.stdout)["result"]
    body_text = text.split("$$SOE")[1].split("$$EOE")[0]
    rows = [line.split(",") for line in body_text.strip().splitlines()]
    if len(rows) != len(times):
        raise SystemExit(f"{body}: asked for {len(times)} rows, got {len(rows)}")
    return rows


def number(field):
    return float(field.strip())   # refuses anything that isn't a plain number


def table(lon, lat, km, count):
    times = [START + i * STEP for i in range(count)]
    # Row: JD, solar flag, lunar flag, azimuth, elevation, [illuminated %,]
    # In batches: the server answered 502 to one request of 60 times.
    sun, moon = [], []
    for i in range(0, count, BATCH):
        part = times[i:i + BATCH]
        sun += query("10", "4", lon, lat, km, part)
        time.sleep(1)
        moon += query("301", "4,10", lon, lat, km, part)
        time.sleep(1)
    out = []
    for t, s, m in zip(times, sun, moon):
        for row in (s, m):
            if abs(number(row[0]) - jd(t)) > 1e-6:
                raise SystemExit(f"time mismatch at {t}: {row[0]}")
        out.append((t, number(s[4]), number(m[4]), number(m[5]) / 100.0))
    return out


def main():
    with open(OUT, "w") as f:
        f.write("/* GENERATED by tools/fetch_ephemeris_reference.py. Do not edit.\n"
                " * Source: NASA/JPL Horizons, airless apparent elevation (quantity 4)\n"
                " * and illuminated fraction (quantity 10), topocentric.\n"
                f" * Fetched {time.strftime('%Y-%m-%d', time.gmtime())}.\n"
                " * Columns: unix seconds, sun altitude deg, moon altitude deg, moon lit fraction. */\n")
        for name, lon, lat, km, count in SITES:
            f.write(f"\nstatic const struct ephem_ref REF_{name}[] = {{\n")
            for t, s, m, k in table(lon, lat, km, count):
                f.write(f"    {{ {t}, {s:.6f}, {m:.6f}, {k:.6f} }},\n")
            f.write("};\n")


if __name__ == "__main__":
    main()
